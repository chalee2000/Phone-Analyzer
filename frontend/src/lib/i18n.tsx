export type TKey = Key;
type Vars = Record<string, string | number>;

const I18nContext = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: TKey | string, v?: Vars) => string }>({
  lang: "th",
  setLang: () => {},
  t: (k) => k,
});

function readLang(): Lang {
  try {
    return (localStorage.getItem("spni.lang") as Lang) || "th";
  } catch {
    return "th";
  }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readLang);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("spni.lang", l);
    } catch {
      /* ignore */
    }
    document.documentElement.lang = l;
  }, []);
  const t = useCallback(
    (key: TKey | string, vars?: Vars) => {
      const table = lang === "th" ? th : en;
      let s = (table as Record<string, string>)[key] ?? (th as Record<string, string>)[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
      return s;
    },
    [lang],
  );
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
